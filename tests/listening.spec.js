const {test,expect}=require('@playwright/test');
const schedule=require('../schedule.json');
test('supplementary listening dates, navigation, filters and independent saved progress',async({page},info)=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.clock.setFixedTime(new Date('2026-11-06T01:00:00Z'));
 await page.goto('./');
 await page.locator('#day-2026-10-22 input').check();
 const link=page.getByRole('link',{name:'Comprehensible Input / Daily Listening'});
 await expect(link).toHaveAttribute('href','./comprehensible-input.html');
 await link.click();
 const cards=page.locator('.day');
 expect(await cards.evaluateAll(cs=>cs.map(c=>c.dataset.date))).toEqual(schedule.filter(r=>r.date>='2026-11-05').map(r=>r.date));
 await expect(cards).toHaveCount(31);
 await expect(page.locator('.day .video.ci')).toHaveCount(31);
 await expect(page.locator('.day .check')).toHaveCount(31);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:`test-results/${info.project.name}-listening.png`});
 await page.locator('#query').fill('2026-11-05');
 await expect(page.locator('.day:visible')).toHaveCount(1);
 await page.locator('#query').fill('');
 await page.locator('#unwatched').check();
 await page.locator('[data-date="2026-11-05"] input').check();
 await expect(page.locator('.day:visible')).toHaveCount(30);
 await page.reload();
 await expect(page.locator('[data-date="2026-11-05"] input')).toBeChecked();
 await page.locator('#query').fill('no-match');
 await expect(page.locator('.day:visible')).toHaveCount(0);
 await page.locator('#today').click();
 await expect(page.locator('.day:visible')).toHaveCount(31);
 await expect(page.locator('[data-date="2026-11-06"]')).toHaveClass(/today/);
 await page.getByRole('link',{name:'← Return to KAI Morning Study Guide'}).click();
 await expect(page.locator('#day-2026-10-22 input')).toBeChecked();
 await expect(page.locator('#progress-text')).toHaveText('1 of 40 watched');
 expect(errors).toEqual([]);
});
